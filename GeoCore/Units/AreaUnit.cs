namespace GeoCore.Units
{
    /// <summary>
    /// Units of measurement for geospatial area calculations.
    /// </summary>
    public enum AreaUnit
    {
        /// <summary>Square kilometres (km²).</summary>
        SquareKilometers,

        /// <summary>Square metres (m²).</summary>
        SquareMeters,

        /// <summary>Square miles (mi²).</summary>
        SquareMiles,

        /// <summary>Hectares (ha), 10,000 m².</summary>
        Hectares,

        /// <summary>Acres (ac), 4,046.8564224 m² exactly.</summary>
        Acres,

        /// <summary>Square feet (ft²).</summary>
        SquareFeet
    }
}
