namespace GeoCore.Units
{
    /// <summary>
    /// Represents the supported units of distance measurement.
    /// </summary>
    public enum DistanceUnit
    {
        /// <summary>Kilometres (1 km = 1,000 metres).</summary>
        Kilometers,

        /// <summary>Metres, the SI base unit of length.</summary>
        Meters,

        /// <summary>Statute miles (1 mile = 1,609.344 metres exactly).</summary>
        Miles,

        /// <summary>Nautical miles (1 NM = 1,852 metres exactly).</summary>
        NauticalMiles,

        /// <summary>International feet (1 foot = 0.3048 metres exactly).</summary>
        Feet,

        /// <summary>International yards (1 yard = 0.9144 metres exactly).</summary>
        Yards,

        /// <summary>Centimetres (1 cm = 0.01 metres).</summary>
        Centimeters,

        /// <summary>Millimetres (1 mm = 0.001 metres).</summary>
        Millimeters,

        /// <summary>International inches (1 inch = 0.0254 metres exactly).</summary>
        Inches
    }
}
